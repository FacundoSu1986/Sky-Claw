def test_no_existe_camino_con_valores_sinteticos(tmp_path: pathlib.Path) -> None:
    """El binder no contiene los literales del camino sintético que FIX 5 elimina.

    Se inspecciona el AST y se excluyen los docstrings: la prosa que EXPLICA el
    defecto no es el defecto. Lo que se busca es un literal que pueda llegar a
    ``PropuestaTransicion``.
    """
    import ast

    arbol = ast.parse(pathlib.Path(binder.__file__).read_text(encoding="utf-8"))
    docstrings: set[int] = set()
    for nodo in ast.walk(arbol):
        if isinstance(nodo, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            cuerpo = nodo.body
            if cuerpo and isinstance(cuerpo[0], ast.Expr) and isinstance(cuerpo[0].value, ast.Constant):
                docstrings.add(id(cuerpo[0].value))
    literales = {
        nodo.value
        for nodo in ast.walk(arbol)
        if isinstance(nodo, ast.Constant) and isinstance(nodo.value, str) and id(nodo) not in docstrings
    }
    for prohibido in ("prev", "cand", "setup-skse-clean", "0" * 64):
        assert prohibido not in literales, f"quedó el literal sintético {prohibido!r} en el código del binder"


