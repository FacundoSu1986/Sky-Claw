@dataclasses.dataclass
class _Rig:
    storage: pathlib.Path
    managed_src: pathlib.Path
    mo2_dir: pathlib.Path
    ini: pathlib.Path
    config: pathlib.Path
    clone_root: pathlib.Path
    gen_id: str
    clone_id: str
    propuesta: PropuestaAprobacion
    consentimiento: ConsentimientoAprobacion

    def ini_bytes(self) -> bytes:
        return self.ini.read_bytes()

    def config_bytes(self) -> bytes:
        return self.config.read_bytes()

    def active_bytes(self) -> bytes:
        return active_state_path(self.storage).read_bytes()


def _montar_rig(
    tmp_path: pathlib.Path, *, emitir_aprobacion: bool = True, setup_clone: str = "setup-skse-clean"
) -> _Rig:
    managed_src = _crear_managed_source_sintetica(tmp_path / "Steam")
    storage = tmp_path / "Storage"
    assert initialize_frozen_runtime_storage(storage).success
    gen_id = _crear_generation_valida(storage)
    clone_root = tmp_path / "Clones" / "Clone1"
    _crear_clone(storage, clone_root, gen_id, "clone-1", setup_verificado=setup_clone, setup_intencionado=setup_clone)
    mo2_dir = tmp_path / "MO2"
    _crear_mo2_instance_sintetica(mo2_dir, game_path=str(managed_src))
    config = _crear_config(tmp_path / "config.toml", skyrim_path=str(managed_src))
    if emitir_aprobacion:
        propuesta, consentimiento = _preparar_aprobacion(
            storage, target_generation_id=gen_id, target_clone_id="clone-1"
        )
    else:
        propuesta = None  # type: ignore[assignment]
        consentimiento = None  # type: ignore[assignment]
    return _Rig(
        storage=storage,
        managed_src=managed_src,
        mo2_dir=mo2_dir,
        ini=mo2_dir / "modorganizer.ini",
        config=config,
        clone_root=clone_root,
        gen_id=gen_id,
        clone_id="clone-1",
        propuesta=propuesta,
        consentimiento=consentimiento,
    )


def _ejecutar(rig: _Rig, *, environ: dict[str, str] | None = None, probes: RuntimeProbes | None = None):
    entorno = {"SKYRIM_PATH": str(rig.managed_src)} if environ is None else environ
    return binder.ejecutar_transicion_binder(
        storage_root=rig.storage,
        mo2_instance_dir=rig.mo2_dir,
        target_clone_id=rig.clone_id,
        propuesta=rig.propuesta,
        consentimiento=rig.consentimiento,
        managed_source_root=rig.managed_src,
        config_path=rig.config,
        environ=entorno,
        probes=probes if probes is not None else _probes_quiescentes(),
    )


