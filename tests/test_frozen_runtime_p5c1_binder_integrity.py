def test_cas_no_sobrescribe_un_estado_cambiado_concurrentemente(tmp_path: pathlib.Path) -> None:
    """Si un tercero cambia ``active.json`` después del snapshot, NO se pisa.

    La escritura concurrente se inyecta en la ventana real del binder: entre la
    captura del snapshot y el CAS UPDATE DESIRED. El binder debe fallar cerrado
    y dejar intacto el estado del tercero.
    """
    rig = _montar_rig(tmp_path)
    real_capturar = recovery.capturar_registro
    active = active_state_path(rig.storage)
    testigo = {
        "schema_version": 2,
        "desired_generation_id": None,
        "desired_clone_id": None,
        "updated_at_ns": 424242,
    }

    def _capturar_y_competir(**kwargs: object) -> recovery.RegistroRecuperacion:
        registro = real_capturar(**kwargs)  # type: ignore[arg-type]
        # Un participante que NO sostiene el lock del binder gana la carrera.
        from sky_claw.local.frozen_runtime.state import write_json_atomic

        write_json_atomic(active, testigo)
        return registro

    with (
        patch.object(recovery, "capturar_registro", side_effect=_capturar_y_competir),
        pytest.raises(binder.BinderCasError, match="CAS UPDATE DESIRED"),
    ):
        _ejecutar(rig)

    assert json.loads(active.read_text(encoding="utf-8"))["updated_at_ns"] == 424242, (
        "el CAS pisó la escritura del tercero"
    )


