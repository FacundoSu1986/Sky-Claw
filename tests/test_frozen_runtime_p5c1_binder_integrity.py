def _runner_script(frontera: str) -> str:
    return f"""
import os, sys, pathlib
REPO = os.environ["P5C1_REPO"]
sys.path.insert(0, REPO)
sys.path.insert(0, os.path.join(REPO, "tests"))
import test_frozen_runtime_p5c1_binder_integrity as fx
fx._correr_hasta_crashear(pathlib.Path(os.environ["P5C1_RIG"]), {frontera!r})
"""


def _correr_hasta_crashear(rig_dir: pathlib.Path, frontera: str) -> None:
    """Cuerpo del subproceso: monta el rig y muere con ``os._exit`` en la frontera.

    ``os._exit`` no corre ``finally`` ni ``except``: es lo más parecido a un
    proceso que muere que se puede hacer desde Python, y es lo que distingue
    "recuperación" de "rollback en el mismo proceso".

    Antes de ejecutar escribe ``antes.json`` con los digests de las superficies:
    el proceso de test NO puede saber el estado previo de otra forma, porque el
    rig lo construyó este subproceso.
    """
    import hashlib
    from unittest.mock import patch as _patch

    with _patch(
        "sky_claw.local.runtime_vault.runtime_observation.read_skyrim_version",
        lambda exe: "1.6.1170.0",
    ):
        rig = _montar_rig(rig_dir)
        probes = RuntimeProbes(
            identity=lambda r: RuntimeIdentity(game_key="skyrimse", game_version="1.6.1170.0"),
            compatibility=lambda r: CompatibilityResult(
                state=RuntimeCompatibility.COMPATIBLE, reason="compatible sintético"
            ),
            processes=lambda: LiveProcessSnapshot(processes=(), indeterminate=False),
        )
        entorno = {"SKYRIM_PATH": str(rig.managed_src)}
        active = active_state_path(rig.storage)

        manifiesto = {
            "storage": str(rig.storage),
            "ini": str(rig.ini),
            "config": str(rig.config),
            "active": str(active),
            "managed_src": str(rig.managed_src),
            "sha_ini": hashlib.sha256(rig.ini.read_bytes()).hexdigest(),
            "sha_config": hashlib.sha256(rig.config.read_bytes()).hexdigest(),
            "sha_active": hashlib.sha256(active.read_bytes()).hexdigest(),
            "transition_id": "55555555-5555-4555-8555-555555555555",
        }
        (rig_dir / "antes.json").write_text(json.dumps(manifiesto), encoding="utf-8")

        if frontera == "ini":
            real_ini = binder.actualizar_game_path_por_handle

            def _ini_y_morir(retenido, valor, *, al_escribir=None):  # type: ignore[no-untyped-def]
                # El escritor real avisa justo ANTES de mutar; el doble tiene que
                # hacer lo mismo o el binder no registra el intento y el rollback
                # trataría su propia escritura como ajena.
                if al_escribir is not None:
                    al_escribir()
                real_ini(retenido, valor)
                os._exit(9)

            parche = _patch.object(binder, "actualizar_game_path_por_handle", side_effect=_ini_y_morir)
        elif frontera == "config":
            real_cfg = binder.persistir_campo

            def _cfg_y_morir(path, campo, valor):  # type: ignore[no-untyped-def]
                real_cfg(path, campo, valor)
                os._exit(9)

            parche = _patch.object(binder, "persistir_campo", side_effect=_cfg_y_morir)
        elif frontera == "entorno":
            real_fase = recovery.marcar_fase_locked

            def _fase_y_morir(handle, root, *, transition_id, fase):  # type: ignore[no-untyped-def]
                if fase is recovery.FaseRecuperacion.DESEADO_ACTUALIZADO:
                    os._exit(9)
                return real_fase(handle, root, transition_id=transition_id, fase=fase)

            parche = _patch.object(recovery, "marcar_fase_locked", side_effect=_fase_y_morir)
        else:  # "active"
            parche = _patch.object(binder, "assess_effective_runtime", side_effect=lambda **k: os._exit(9))

        with parche:
            binder.ejecutar_transicion_binder(
                storage_root=rig.storage,
                mo2_instance_dir=rig.mo2_dir,
                target_clone_id=rig.clone_id,
                propuesta=rig.propuesta,
                consentimiento=rig.consentimiento,
                managed_source_root=rig.managed_src,
                config_path=rig.config,
                environ=entorno,
                probes=probes,
                transition_id=manifiesto["transition_id"],
            )
        os._exit(0)


@pytest.mark.parametrize("frontera", ["ini", "config", "entorno", "active"])
def test_reinicio_tras_cada_frontera_mutante_recupera_las_superficies(tmp_path: pathlib.Path, frontera: str) -> None:
    """Un proceso NUEVO evalúa las superficies desde el registro durable.

    Para cada frontera mutante (INI, config, entorno, active.json) se hace morir
    un subproceso justo después de esa mutación y antes de la siguiente. El
    proceso de test —que no comparte memoria con el muerto— recupera con
    ``recuperar_transicion_interrumpida``.

    NOTA DE SEGURIDAD (tercera ronda #851): la recuperación en proceso nuevo no
    atribuye escrituras completas porque no puede probar autoría (la fase se
    marca ANTES de escribir). Por eso el estado es
    ``RESTAURACION_INCOMPLETA_REQUIERE_DUENO``: las superficies mutadas se
    conservan como evidencia y la decisión es del propietario.
    """
    rig_dir = tmp_path / "rig"
    rig_dir.mkdir()

    script = tmp_path / "runner.py"
    script.write_text(_runner_script(frontera), encoding="utf-8")
    entorno_proc = dict(os.environ)
    entorno_proc["P5C1_REPO"] = str(_REPO)
    entorno_proc["P5C1_RIG"] = str(rig_dir)
    entorno_proc["PYTHONPATH"] = str(_REPO)
    completado = subprocess.run(
        [sys.executable, str(script)],
        env=entorno_proc,
        capture_output=True,
        timeout=300,
        check=False,
    )
    assert completado.returncode == 9, (
        f"el subproceso no murió en la frontera {frontera}: rc={completado.returncode} "
        f"stdout={completado.stdout[-2000:]!r} stderr={completado.stderr[-2000:]!r}"
    )

    manifiesto = json.loads((rig_dir / "antes.json").read_text(encoding="utf-8"))
    ini = pathlib.Path(manifiesto["ini"])
    config = pathlib.Path(manifiesto["config"])
    active = pathlib.Path(manifiesto["active"])

    def _sha(ruta: pathlib.Path) -> str:
        return hashlib.sha256(ruta.read_bytes()).hexdigest()

    # El crash dejó una mutación REAL en disco (si no, el test no probaría nada).
    if frontera == "ini":
        assert _sha(ini) != manifiesto["sha_ini"]
    elif frontera == "config":
        assert _sha(config) != manifiesto["sha_config"]
    elif frontera == "active":
        assert _sha(active) != manifiesto["sha_active"]

    # Contexto NUEVO: diccionario de entorno vacío, ningún objeto del muerto.
    entorno_nuevo: dict[str, str] = {}
    resultado = recovery.recuperar_transicion_interrumpida(
        pathlib.Path(manifiesto["storage"]),
        transition_id=manifiesto["transition_id"],
        environ=entorno_nuevo,
    )

    assert resultado.estado is recovery.EstadoRecuperacion.RESTAURACION_INCOMPLETA_REQUIERE_DUENO
    assert resultado.requiere_dueno is True
    # La recuperación en proceso nuevo no atribuye escrituras completas del INI
    # (tri-estado #851). Las demás superficies (config, active) usan su
    # discriminador propio sin tri-estado. Lo que importa es que el estado sea
    # INCOMPLETA y que al menos UNA superficie quede sin restaurar.
    ajenas = [v.kind for v in resultado.verificaciones if v.escritura_ajena]
    assert ajenas, f"se esperaba al menos una superficie no atribuida, hay {ajenas}"
    # Verificar que el INI —que SIEMPRE se muta— NO se restauró, porque es la
    # superficie que tiene tri-estado y la recuperación en proceso nuevo no
    # puede probar autoría.
    assert _sha(ini) != manifiesto["sha_ini"], "el INI se restauró sin evidencia de autoría"
    # El entorno se restaura según la fase alcanzada (no usa tri-estado).
    # En ini/config murió antes de escribir el entorno; en entorno/active sí.
    if frontera in ("entorno", "active"):
        assert entorno_nuevo.get("SKYRIM_PATH") == manifiesto["managed_src"]
    else:
        assert "SKYRIM_PATH" not in entorno_nuevo
    # El journal NO se reescribe: la clasificación es de su dueño.
    assert (
        cargar_journal_transicion(pathlib.Path(manifiesto["storage"])).disposition
        is JournalDisposition.PENDING_PROMOTION
    )


