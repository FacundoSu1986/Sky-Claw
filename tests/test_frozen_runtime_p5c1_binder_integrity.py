def test_post_verify_relee_el_config_persistido(tmp_path: pathlib.Path) -> None:
    """POST VERIFY usa el valor RELEÍDO, no la ruta objetivo que el binder decidió.

    Se fuerza que la relectura del POST devuelva otra ruta: si el oráculo
    recibiera ``str(target_clone_root)`` —lo que hacía el PR— la transición
    pasaría igual. Rechazarla demuestra que el valor viene del disco.
    """
    rig = _montar_rig(tmp_path)
    real = binder._leer_skyrim_path_persistido
    llamadas: list[str | None] = []

    def _secuencia(config_path: pathlib.Path | None) -> str | None:
        valor = real(config_path)
        llamadas.append(valor)
        # 1ª: preflight inicial; 2ª: VERIFY EFFECTIVE; 3ª: POST VERIFY.
        if len(llamadas) >= 3:
            return r"C:\Divergente\Skyrim"
        return valor

    with (
        patch.object(binder, "_leer_skyrim_path_persistido", side_effect=_secuencia),
        pytest.raises(binder.BinderVerificationError, match="POST VERIFY"),
    ):
        _ejecutar(rig)


