def _crear_generation_valida(storage_root: pathlib.Path) -> str:
    staging = storage_root / "_staging_gen"
    if staging.exists():
        shutil.rmtree(staging)
    _crear_arbol_juego(staging)
    (staging / "extra.dat").write_bytes(b"extra")
    files = inventory_tree(staging)
    crit = next(f for f in files if f.rel_path == "SkyrimSE.exe")
    evidencia = SourceSnapshotEvidence(
        observed_at_ns=1000,
        provider=ManagedSourceProvider.STEAM,
        game_key="skyrimse",
        files=files,
        critical_files=(crit,),
        provider_metadata=ProviderMetadataObservation(
            provider=ManagedSourceProvider.STEAM, appid="489830", buildid="13189953"
        ),
        runtime_identity=RuntimeIdentity(game_key="skyrimse", game_version="1.6.1170.0"),
        tree_digest=tree_digest_from_files(files),
    )
    meta = registrar_generation_metadata(storage_root, evidencia)
    gen_dir = storage_root / "versions" / meta.generation_id
    if gen_dir.exists():
        shutil.rmtree(gen_dir)
    shutil.copytree(staging, gen_dir)
    shutil.rmtree(staging)
