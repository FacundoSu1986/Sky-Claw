def test_rollback_restaura_ini_config_active_y_entorno(tmp_path: pathlib.Path) -> None:
    """Un fallo DESPUÉS del CAS de ``active.json`` devuelve las cuatro superficies.

    Es el caso que el PR dejaba abierto: el snapshot capturaba
    ``active_state_bytes`` y jamás lo restauraba. El test compara BYTES de las
    cuatro superficies, no sólo el INI, y exige que ``active.json`` vuelva a su
    contenido previo (no que quede el del binder).
    """
    rig = _montar_rig(tmp_path)
    ini_antes = rig.ini_bytes()
    config_antes = rig.config_bytes()
    active_antes = rig.active_bytes()
    entorno = {"SKYRIM_PATH": str(rig.managed_src)}

    with (
        patch.object(binder, "assess_effective_runtime", side_effect=RuntimeError("POST VERIFY revienta")),
        pytest.raises(RuntimeError, match="POST VERIFY revienta"),
    ):
        _ejecutar(rig, environ=entorno)

    assert rig.ini_bytes() == ini_antes, "modorganizer.ini no volvió a su estado previo"
    assert rig.config_bytes() == config_antes, "config.toml no volvió a su estado previo"
    assert rig.active_bytes() == active_antes, "state/active.json no volvió a su estado previo"
    assert entorno["SKYRIM_PATH"] == str(rig.managed_src), "SKYRIM_PATH no volvió a su valor previo"


