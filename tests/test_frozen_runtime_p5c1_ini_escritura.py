"""Escritura de ``modorganizer.ini`` con equivalencia Qt verificable (P5-C1, FIX 8).

Tracker: #672
ADR 0012 §13, §29.4

El defecto que estos tests cierran: ``actualizar_game_path_en_ini`` decodificaba
el INI completo, lo reescribía y **volvía a anteponer el BOM** que ya venía
dentro del texto decodificado. El resultado era un archivo con dos BOM, que
ningún lector Qt interpreta igual que el original.

La regla que se ancla acá: la escritura es **quirúrgica a nivel de bytes**.
Todo lo que no es la línea ``gamePath`` se preserva byte a byte, el BOM se
conserva exactamente una vez, y el valor se codifica en ASCII puro con la
semántica de escape que el lector de Qt (``_desescapar_bytes``) ya emula.

``QT_QSETTINGS_EQUIVALENCE = NOT_CLAIMED``: en este entorno no hay Qt
instalado, así que la equivalencia con ``QSettings`` no se puede DEMOSTRAR
ejecutándola. Por eso el módulo restringe explícitamente los formatos
admitidos y falla cerrado en el resto (ver ``test_formato_no_admitido...``).
"""

from __future__ import annotations

import pathlib

import pytest

from sky_claw.local.frozen_runtime.effective_runtime.mo2_ini import (
    leer_ejecutables_de_mo2,
    leer_game_path_de_mo2,
)
from sky_claw.local.frozen_runtime.effective_runtime.models import ObservationState
from sky_claw.local.frozen_runtime.mo2_ini_escritura import (
    EscrituraIniNoVerificadaError,
    FormatoIniNoAdmitidoError,
    actualizar_game_path_en_ini,
    codificar_qt_byte_array,
)

#: INI realista de MO2 2.5.2: comentarios, secciones, claves ajenas, CRLF.
_INI_CRLF = (
    b"; This file was automatically generated by Mod Organizer.\r\n"
    b"[General]\r\n"
    b"gamePath=@ByteArray(C:\\\\Steam\\\\steamapps\\\\common\\\\Skyrim Special Edition)\r\n"
    b"gameName=SkyrimSE\r\n"
    b"firstStart=false\r\n"
    b"\r\n"
    b"[customExecutables]\r\n"
    b"1\\title=Skyrim Special Edition\r\n"
    b"1\\binary=C:/Steam/steamapps/common/Skyrim Special Edition/SkyrimSE.exe\r\n"
    b"size=2\r\n"
    b"\r\n"
    b"[Settings]\r\n"
    b"Language=en_US\r\n"
)

_INI_LF = _INI_CRLF.replace(b"\r\n", b"\n")


def _escribir_ini(path: pathlib.Path, contenido: bytes) -> pathlib.Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(contenido)
    return path


def _lineas(contenido: bytes) -> list[bytes]:
    """Líneas SIN separador, para comparar byte a byte preservando el resto."""
    return contenido.replace(b"\r\n", b"\n").split(b"\n")


def _lineas_sin_game_path(contenido: bytes) -> list[bytes]:
    return [linea for linea in _lineas(contenido) if not linea.strip().lower().startswith(b"gamepath=")]


# ---------------------------------------------------------------------------
# BOM: se conserva UNA vez, nunca se duplica
# ---------------------------------------------------------------------------


@pytest.mark.parametrize("contenido", [_INI_CRLF, _INI_LF], ids=["crlf", "lf"])
def test_el_bom_no_se_duplica(tmp_path: pathlib.Path, contenido: bytes) -> None:
    """Un INI con BOM conserva EXACTAMENTE un BOM tras la escritura.

    El defecto original: ``decode('utf-8')`` deja ``\\ufeff`` como primer
    carácter, y el escritor volvía a anteponer ``b'\\xef\\xbb\\xbf'``. El
    archivo quedaba con dos BOM y MO2 leía la primera clave como basura.
    """
    ini = _escribir_ini(tmp_path / "MO2" / "modorganizer.ini", b"\xef\xbb\xbf" + contenido)

    actualizar_game_path_en_ini(ini, r"C:\Modding\Clone P5C1")

    despues = ini.read_bytes()
    assert despues.startswith(b"\xef\xbb\xbf")
    assert not despues.startswith(b"\xef\xbb\xbf\xef\xbb\xbf")
    assert despues.count(b"\xef\xbb\xbf") == 1


@pytest.mark.parametrize("contenido", [_INI_CRLF, _INI_LF], ids=["crlf", "lf"])
def test_sin_bom_no_se_agrega_bom(tmp_path: pathlib.Path, contenido: bytes) -> None:
    """Un INI sin BOM sigue sin BOM: no se inventa una marca de codificación."""
    ini = _escribir_ini(tmp_path / "MO2" / "modorganizer.ini", contenido)

    actualizar_game_path_en_ini(ini, r"C:\Modding\Clone P5C1")

    assert not ini.read_bytes().startswith(b"\xef\xbb\xbf")


# ---------------------------------------------------------------------------
# Preservación byte a byte de todo lo que no es la línea gamePath
# ---------------------------------------------------------------------------


@pytest.mark.parametrize(
    "contenido",
    [b"\xef\xbb\xbf" + _INI_CRLF, _INI_CRLF, b"\xef\xbb\xbf" + _INI_LF, _INI_LF],
    ids=["bom-crlf", "crlf", "bom-lf", "lf"],
)
def test_preserva_bytes_ajenos_byte_a_byte(tmp_path: pathlib.Path, contenido: bytes) -> None:
    """Comentarios, secciones, claves y ejecutables quedan IDÉNTICOS.

    La comparación es sobre las líneas restantes, no sobre una re-serialización:
    un escritor que normalice saltos de línea o reordene claves cambia estos
    bytes y el test lo ve.
    """
    ini = _escribir_ini(tmp_path / "MO2" / "modorganizer.ini", contenido)

    actualizar_game_path_en_ini(ini, r"C:\Modding\Clone P5C1")

    despues = ini.read_bytes()
    assert _lineas_sin_game_path(despues) == _lineas_sin_game_path(contenido)
    # Y la línea reemplazada es exactamente una: no se insertó ni se perdió nada.
    assert len(_lineas(despues)) == len(_lineas(contenido))


@pytest.mark.parametrize("contenido", [_INI_CRLF, _INI_LF], ids=["crlf", "lf"])
def test_conserva_el_salto_de_linea_del_archivo(tmp_path: pathlib.Path, contenido: bytes) -> None:
    """La línea nueva usa el MISMO separador que el resto del archivo.

    Un INI CRLF con una línea LF suelta es un archivo mixto que Qt tolera pero
    que ningún test previo distinguía.
    """
    ini = _escribir_ini(tmp_path / "MO2" / "modorganizer.ini", contenido)

    actualizar_game_path_en_ini(ini, r"C:\Modding\Clone P5C1")

    despues = ini.read_bytes()
    if b"\r\n" in contenido:
        assert b"\r\n" in despues
        assert b"gamePath=" in despues and b"\n" in despues
        # Ninguna línea LF suelta: todo \n va precedido de \r.
        assert despues.replace(b"\r\n", b"").count(b"\n") == 0
    else:
        assert b"\r" not in despues


# ---------------------------------------------------------------------------
# Codificación Qt: ASCII puro, recíproca con el lector, sin ambigüedad de hex
# ---------------------------------------------------------------------------


@pytest.mark.parametrize(
    "ruta",
    [
        r"C:\Modding\Skyrim Clone 1.6.1170",
        r"C:\Modding\Clon (P5C1) [beta]",
        "C:/Modding/Clone con barras",
        r"C:\Modding\Añejo\Clonación",
        r"C:\Modding\克隆\运行时",
        r"C:\Modding\Clon;con#raros,=y[]parentesis)",
        r"D:\a\b\c\d\e\f",
        r"C:\Modding\x41x41",
        r"C:\Modding\ñ1a",
    ],
)
def test_codificacion_es_ascii_pura_y_reciproca(tmp_path: pathlib.Path, ruta: str) -> None:
    """Toda ruta se codifica en ASCII y el lector de Qt la recupera EXACTA.

    ``@ByteArray`` de Qt es un byte array escapado: los bytes fuera de ASCII se
    emiten como ``\\xNN``. Emitir Unicode crudo dentro de ``@ByteArray(...)``
    produce un archivo que nuestro lector entiende pero que no es lo que Qt
    escribe, y la equivalencia deja de ser demostrable.
    """
    ini = _escribir_ini(tmp_path / "MO2" / "modorganizer.ini", _INI_CRLF)

    actualizar_game_path_en_ini(ini, ruta)

    crudo = ini.read_bytes()
    linea = next(linea for linea in crudo.split(b"\n") if linea.strip().lower().startswith(b"gamepath="))
    valor = linea.split(b"=", 1)[1].strip()
    assert valor.isascii(), f"el valor escapado no es ASCII: {valor!r}"

    evidencia = leer_game_path_de_mo2(ini)
    assert evidencia.state is ObservationState.OBSERVED
    assert evidencia.path == ruta


def test_escape_hex_no_se_come_el_digito_siguiente(tmp_path: pathlib.Path) -> None:
    """``\\xNN`` seguido de un dígito hexadecimal no se fusiona en un escape mayor.

    El lector de Qt acumula TODOS los dígitos hex sucesivos (``\\x0d9`` es UN
    byte 0xD9). Un escritor que emita ``\\xc3`` y después el literal ``1``
    produce ``\\xc31`` = 0xC31, que excede 0xFF y el lector declara
    irrecuperable. La ruta de este test tiene esa forma exacta.
    """
    ini = _escribir_ini(tmp_path / "MO2" / "modorganizer.ini", _INI_CRLF)
    ruta = "C:\\Modding\\ñ1a"

    actualizar_game_path_en_ini(ini, ruta)

    evidencia = leer_game_path_de_mo2(ini)
    assert evidencia.state is ObservationState.OBSERVED
    assert evidencia.path == ruta


def test_codificar_qt_byte_array_es_ascii_y_estable() -> None:
    """La función pública de codificación no emite caracteres no-ASCII."""
    codificado = codificar_qt_byte_array(r"C:\Modding\Añejo (1)")
    assert codificado.startswith("@ByteArray(")
    assert codificado.endswith(")")
    assert codificado.isascii()


# ---------------------------------------------------------------------------
# Formatos NO admitidos: fallar cerrado en vez de adivinar
# ---------------------------------------------------------------------------


@pytest.mark.parametrize(
    ("nombre", "contenido"),
    [
        ("utf16-le-bom", b"\xff\xfe" + "[General]\r\ngamePath=x\r\n".encode("utf-16-le")),
        ("utf16-be-bom", b"\xfe\xff" + "[General]\r\ngamePath=x\r\n".encode("utf-16-be")),
        ("nul-embebido", b"[General]\r\ngamePath=@ByteArray(C:\\a)\r\n\x00\x00"),
        ("saltos-mixtos", b"[General]\r\ngamePath=@ByteArray(C:\\a)\ngameName=SkyrimSE\r\n"),
        ("cr-solo", b"[General]\rgamePath=@ByteArray(C:\\a)\r"),
    ],
    ids=["utf16-le", "utf16-be", "nul", "mixtos", "cr"],
)
def test_formato_no_admitido_falla_cerrado(tmp_path: pathlib.Path, nombre: str, contenido: bytes) -> None:
    """Formatos cuya equivalencia Qt no se puede demostrar se RECHAZAN.

    ``QT_QSETTINGS_EQUIVALENCE = NOT_CLAIMED``: sin Qt en el entorno, admitir
    UTF-16 o saltos mixtos sería afirmar una preservación que nadie verifica.
    El switch falla cerrado en vez de escribir un INI que MO2 podría no leer.
    """
    ini = _escribir_ini(tmp_path / "MO2" / "modorganizer.ini", contenido)
    antes = ini.read_bytes()

    with pytest.raises(FormatoIniNoAdmitidoError):
        actualizar_game_path_en_ini(ini, r"C:\Modding\Clone P5C1")

    assert ini.read_bytes() == antes, "un formato rechazado NO puede dejar el archivo mutado"


def test_ini_inexistente_falla_cerrado(tmp_path: pathlib.Path) -> None:
    """Sin archivo no hay nada que preservar: se falla cerrado, no se crea uno."""
    ini = tmp_path / "MO2" / "modorganizer.ini"

    with pytest.raises(FormatoIniNoAdmitidoError):
        actualizar_game_path_en_ini(ini, r"C:\Modding\Clone P5C1")

    assert not ini.exists()


