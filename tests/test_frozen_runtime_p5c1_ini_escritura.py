# Verificación post-escritura: el readback es la puerta, no una formalidad
# ---------------------------------------------------------------------------


def test_verificacion_post_escritura_detecta_divergencia(
    tmp_path: pathlib.Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Si el readback no devuelve la ruta pedida, la escritura NO se declara buena.

    Se simula un escritor que "funciona" (bytes escritos) pero cuyo resultado el
    lector de MO2 interpreta distinto: el caso de un escape mal formado. La
    verificación tiene que atajarlo en la escritura, no en POST VERIFY.
    """
    ini = _escribir_ini(tmp_path / "MO2" / "modorganizer.ini", _INI_CRLF)

    monkeypatch.setattr(
        "sky_claw.local.frozen_runtime.mo2_ini_escritura.leer_game_path_de_mo2",
        lambda _p: type(
            "Falsa",
            (),
            {"state": ObservationState.OBSERVED, "path": r"C:\Otra\Ruta", "detail": ""},
        )(),
    )

    with pytest.raises(EscrituraIniNoVerificadaError, match="verificación"):
        actualizar_game_path_en_ini(ini, r"C:\Modding\Clone P5C1")


def test_el_ini_resultante_es_leible_por_los_lectores_de_mo2(tmp_path: pathlib.Path) -> None:
    """El archivo final lo leen los dos lectores que MO2 usa: gamePath y ejecutables."""
    ini = _escribir_ini(tmp_path / "MO2" / "modorganizer.ini", _INI_CRLF)

    actualizar_game_path_en_ini(ini, r"C:\Modding\Clon (P5C1)")

    assert leer_game_path_de_mo2(ini).path == r"C:\Modding\Clon (P5C1)"
    ejecutables = leer_ejecutables_de_mo2(ini)
    assert len(ejecutables) == 1
    assert ejecutables[0].title == "Skyrim Special Edition"


def test_ini_sin_seccion_general_la_crea_sin_perder_nada(tmp_path: pathlib.Path) -> None:
    """Un INI sin ``[General]`` recibe la sección, y el resto sobrevive intacto."""
    contenido = b"[Settings]\r\nLanguage=en_US\r\n"
    ini = _escribir_ini(tmp_path / "MO2" / "modorganizer.ini", contenido)

    actualizar_game_path_en_ini(ini, r"C:\Modding\Clone P5C1")

    despues = ini.read_bytes()
    assert b"[General]" in despues
    assert b"[Settings]\r\nLanguage=en_US\r\n" in despues
    assert leer_game_path_de_mo2(ini).path == r"C:\Modding\Clone P5C1"


def test_ini_sin_game_path_lo_inserta_en_general(tmp_path: pathlib.Path) -> None:
    """``[General]`` sin ``gamePath`` recibe la clave sin tocar sus hermanas."""
    contenido = b"[General]\r\ngameName=SkyrimSE\r\n\r\n[Settings]\r\nLanguage=en_US\r\n"
    ini = _escribir_ini(tmp_path / "MO2" / "modorganizer.ini", contenido)

    actualizar_game_path_en_ini(ini, r"C:\Modding\Clone P5C1")

    despues = ini.read_bytes()
    assert b"gameName=SkyrimSE" in despues
    assert despues.index(b"gamePath=") < despues.index(b"[Settings]")
    assert leer_game_path_de_mo2(ini).path == r"C:\Modding\Clone P5C1"
