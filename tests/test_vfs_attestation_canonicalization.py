def test_binding_de_source_mod(tmp_path: pathlib.Path) -> None:
    """El mismo archivo canario en otro mod cambia el fingerprint."""
    canary = _crear_perfil(tmp_path / "a", plugins=_PLUGINS_BASE, modlist="+CanaryMod\n")
