def test_framing_del_digest_evita_colision_por_reparto_de_bytes(tmp_path: pathlib.Path) -> None:
    """Dos estados distintos no pueden producir el mismo digest por reencuadre.

    Con la concatenación sin largo de v1, `modlist.txt` vacío + `loadorder.txt`
    con el literal ``\\0file\\0loadorder.txt`` producía exactamente el mismo
    material que el reparto inverso (colisión verificada sobre el esquema v1).
    El framing length-prefixed lo cierra.
    """
    imitacion = b"\x00file\x00settings.ini"

    vacio = _crear_perfil(tmp_path / "a", plugins=_PLUGINS_BASE)
    (vacio.profile_dir / "loadorder.txt").write_bytes(b"")
    (vacio.profile_dir / "settings.ini").write_bytes(imitacion)
    imitado = _crear_perfil(tmp_path / "b", plugins=_PLUGINS_BASE)
    (imitado.profile_dir / "loadorder.txt").write_bytes(imitacion)
    (imitado.profile_dir / "settings.ini").write_bytes(b"")

    # El esquema v1 (previo a #633) colisionaba: mismo material de digest.
    assert _digest_v1(vacio, vacio.challenge()) == _digest_v1(imitado, imitado.challenge())
    # El esquema v2 los distingue.
    assert vacio.challenge().profile_fingerprint != imitado.challenge().profile_fingerprint


def _digest_v1(perfil: _Perfil, challenge: VfsAttestationChallenge) -> str:
    """Reimplementación local del digest v1 (crudo) para anclar el bump de dominio."""
    digest = hashlib.sha256()
    digest.update(b"skyclaw-vfs-profile-v1\0")
    digest.update(perfil.profile.encode("utf-8"))
    for filename in ("modlist.txt", "plugins.txt", "loadorder.txt", "settings.ini", "settings.txt"):
        path = perfil.profile_dir / filename
        digest.update(b"\0file\0")
        digest.update(filename.encode("ascii"))
        try:
            digest.update(path.read_bytes())
        except FileNotFoundError:
            digest.update(b"\0missing\0")
    digest.update(b"\0canary\0")
    digest.update(challenge.source_mod.encode("utf-8"))
    digest.update(challenge.relative_path.as_posix().encode("utf-8"))
    digest.update(challenge.sha256.encode("ascii"))
    return digest.hexdigest()
