"""Contrato semántico del fingerprint de perfil de la attestation VFS (#633).

El rig real de PR-586C (Windows, MO2 2.5.2 + USVFS) falló cerrado porque
`startApplication` reserializa `plugins.txt` entre el preview y el worker:
141 B → 96 B con la lista de plugins semánticamente intacta. Estos tests anclan
las dos mitades del contrato:

* **tolerado**: lo que MO2 puede reescribir sin cambiar el estado del perfil
  (BOM, header, EOL, líneas deshabilitadas, líneas de masters oficiales);
* **fail-closed**: todo cambio que sí cambia qué plugins carga el motor.

La evidencia de la semántica está en `CreationGamePlugins::readPluginList` /
`writePluginList` de MO2 (2.5.2 → master) y en el rig real referenciado en #633.
"""

from __future__ import annotations

import dataclasses
import hashlib
import pathlib

import pytest

from sky_claw.local.mo2.vfs_attestation import (
    VfsAttestationChallenge,
    VfsAttestationError,
    build_attestation_challenge,
    verify_vfs_attestation,
)

_MO2_HEADER = b"# This file was automatically generated by Mod Organizer.\r\n"
_UTF8_BOM = b"\xef\xbb\xbf"
_RIG_PROFILE = "SkyClaw-PR2-Rig"
_RIG_MASTERS = ("Skyrim.esm", "Update.esm", "Dawnguard.esm", "HearthFires.esm", "Dragonborn.esm")
_CANARY_RELATIVE = pathlib.PurePosixPath("SKSE/Plugins/skyclaw-canary.txt")
_CANARY_BYTES = b"canary-v1"
_ERROR_FINGERPRINT = "fingerprint del perfil cambió después del preview"


@dataclasses.dataclass(frozen=True, slots=True)
class _Perfil:
    """Fixture de perfil MO2 mínimo, con la vista virtual del canary ya montada."""

    mo2_root: pathlib.Path
    profile_dir: pathlib.Path
    game_root: pathlib.Path
    physical_data: pathlib.Path
    virtual_data: pathlib.Path
    profile: str

    def escribir_cc(self, nombres: tuple[str, ...]) -> None:
        """Declara contenido de Creation Club como lo hace el juego (`Skyrim.ccc`)."""
        if not nombres:
            return
        (self.game_root / "Skyrim.ccc").write_bytes(b"".join(nombre.encode("ascii") + b"\r\n" for nombre in nombres))

    def escribir_plugins(self, contenido: bytes) -> None:
        (self.profile_dir / "plugins.txt").write_bytes(contenido)

    def challenge(self) -> VfsAttestationChallenge:
        return build_attestation_challenge(
            mo2_root=self.mo2_root,
            profile=self.profile,
            physical_data_dir=self.physical_data,
        )

    def verificar(self, challenge: VfsAttestationChallenge) -> None:
        verify_vfs_attestation(
            challenge=challenge,
            mo2_root=self.mo2_root,
            profile=self.profile,
            virtual_data_dir=self.virtual_data,
        )


def _crear_perfil(
    tmp_path: pathlib.Path,
    *,
    plugins: bytes | None = None,
    profile: str = _RIG_PROFILE,
    modlist: str = "+CanaryMod\n-OtherMod\n",
    canary_relativo: pathlib.PurePosixPath = _CANARY_RELATIVE,
    canary_bytes: bytes = _CANARY_BYTES,
    cc: tuple[str, ...] = (),
) -> _Perfil:
    """Perfil MO2 mínimo con los dos `Data` colgando del MISMO game root.

    En producción el preview lee el `Data` físico y el worker lee el mismo
    `<juego>/Data` a través de USVFS, así que ambos derivan de ahí el mismo
    `primaryPlugins()` (masters + `Skyrim.ccc`). Acá son directorios distintos
    sólo para poder modelar que el canary NO existe en el `Data` físico.
    """
    mo2_root = tmp_path / "MO2"
    profile_dir = mo2_root / "profiles" / profile
    game_root = tmp_path / "Skyrim"
    physical_data = game_root / "Data"
    for directorio in (profile_dir, physical_data):
        directorio.mkdir(parents=True, exist_ok=True)
    (profile_dir / "modlist.txt").write_text(modlist, encoding="utf-8-sig")
    for mod_name in ("CanaryMod", "OtherMod", "ZebraMod"):
        canary = mo2_root / "mods" / mod_name / pathlib.Path(*canary_relativo.parts)
        canary.parent.mkdir(parents=True, exist_ok=True)
        canary.write_bytes(canary_bytes)
    perfil = _Perfil(
        mo2_root=mo2_root,
        profile_dir=profile_dir,
        game_root=game_root,
        physical_data=physical_data,
        virtual_data=game_root / "Data-en-vivo",
        profile=profile,
    )
    visible = perfil.virtual_data / pathlib.Path(*canary_relativo.parts)
    visible.parent.mkdir(parents=True, exist_ok=True)
    visible.write_bytes(canary_bytes)
    if plugins is not None:
        perfil.escribir_plugins(plugins)
    perfil.escribir_cc(cc)
    return perfil


