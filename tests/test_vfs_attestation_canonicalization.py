def _plugins_rig_antes() -> bytes:
    """Forma pre-lanzamiento: BOM + header + masters oficiales con estrella.

    Reproduce el tamaño observado (141 B): 3 (BOM) + 59 (header CRLF) + 77
    (cinco líneas ``*master``) + 2 (línea vacía final).
    """
    masters = b"".join(b"*" + name.encode("ascii") + b"\r\n" for name in _RIG_MASTERS)
    return _UTF8_BOM + _MO2_HEADER + masters + b"\r\n"


def _plugins_rig_despues() -> bytes:
    """Forma que escribe MO2 al lanzar: header + plugins no oficiales sin estrella.

    Reproduce el tamaño observado (96 B): 59 (header) + 18 + 19 (dos entradas
    deshabilitadas de 16 y 17 caracteres).
    """
    return _MO2_HEADER + b"RigCanaryMod.esp\r\n" + b"SkyClawCanary.esp\r\n"


def test_regresion_rig_real_reproduce_las_formas_observadas() -> None:
    """Ancla de fidelidad: las formas sintéticas miden 141 B y 96 B como el rig."""
    assert len(_plugins_rig_antes()) == 141
    assert len(_plugins_rig_despues()) == 96


def test_regresion_rig_real_la_reserializacion_de_mo2_no_cambia_el_fingerprint(tmp_path: pathlib.Path) -> None:
    """MO2 reescribe plugins.txt entre preview y worker: la attestation sigue OK."""
    perfil = _crear_perfil(tmp_path, plugins=_plugins_rig_antes())

    challenge = perfil.challenge()
    perfil.escribir_plugins(_plugins_rig_despues())
    perfil.verificar(challenge)

    assert challenge.profile_fingerprint == perfil.challenge().profile_fingerprint


def test_regresion_rig_real_un_vecino_semantico_sigue_fallando(tmp_path: pathlib.Path) -> None:
    """La misma forma que MO2 escribe, con un plugin más, NO es una reserialización."""
    perfil = _crear_perfil(tmp_path, plugins=_plugins_rig_antes())

    challenge = perfil.challenge()
    perfil.escribir_plugins(_plugins_rig_despues() + b"*RigExtra.esp\r\n")
    assert perfil.challenge().profile_fingerprint != challenge.profile_fingerprint
    with pytest.raises(VfsAttestationError, match=_ERROR_FINGERPRINT):
        perfil.verificar(challenge)


def test_regresion_rig_real_el_canary_y_el_resto_del_perfil_cambian_el_digest(tmp_path: pathlib.Path) -> None:
    """La tolerancia es solo de representación: los bytes crudos siguen contando."""
    perfil = _crear_perfil(tmp_path, plugins=_plugins_rig_antes())
    original = perfil.challenge().profile_fingerprint

    (perfil.profile_dir / "loadorder.txt").write_bytes(_MO2_HEADER + b"Skyrim.esm\r\n")
    con_loadorder = perfil.challenge().profile_fingerprint

    assert con_loadorder != original


