def test_binding_de_source_mod_con_el_mismo_archivo_y_los_mismos_bytes(tmp_path: pathlib.Path) -> None:
    """Dos mods con el mismo archivo canario: solo el mod de origen distingue el estado.

    `modlist.txt` crudo y el SHA del canario son idénticos en ambos intentos; el
    único cambio es cuál mod aporta el archivo (borrar la copia de mayor
    prioridad degrada el canary a la copia siguiente). Si el digest no atara
    `source_mod`, un challenge emitido para un mod reutilizaría el fingerprint
    de otro.
    """
    perfil = _crear_perfil(tmp_path, plugins=_PLUGINS_BASE, modlist="+CanaryMod\n+ZebraMod\n")
    original = perfil.challenge()
    assert original.source_mod == "ZebraMod"

    (perfil.mo2_root / "mods" / "ZebraMod" / pathlib.Path(*_CANARY_RELATIVE.parts)).unlink()
    degradado = perfil.challenge()

    assert degradado.source_mod == "CanaryMod"
    assert degradado.sha256 == original.sha256
    assert degradado.profile_fingerprint != original.profile_fingerprint


