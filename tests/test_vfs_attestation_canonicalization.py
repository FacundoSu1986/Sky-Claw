def test_representaciones_equivalentes_comparten_fingerprint(
    tmp_path: pathlib.Path,
    descripcion: str,  # noqa: ARG001 — id legible en el reporte de pytest
    contenido: bytes,
) -> None:
    """Toda reserialización demostrada como neutra conserva el fingerprint."""
    perfil = _crear_perfil(tmp_path, plugins=_PLUGINS_BASE)
    base = perfil.challenge()

    perfil.escribir_plugins(contenido)
    perfil.verificar(base)

    assert base.profile_fingerprint == perfil.challenge().profile_fingerprint


def test_plugins_txt_ausente_vacio_o_solo_header_son_el_mismo_estado(tmp_path: pathlib.Path) -> None:
    """Sin plugins no oficiales habilitados el estado es el mismo, exista o no el archivo."""
    solo_header = _crear_perfil(tmp_path / "a", plugins=_MO2_HEADER)
    vacio = _crear_perfil(tmp_path / "b", plugins=b"")
    ausente = _crear_perfil(tmp_path / "c")

    assert solo_header.challenge().profile_fingerprint == vacio.challenge().profile_fingerprint
    assert solo_header.challenge().profile_fingerprint == ausente.challenge().profile_fingerprint


def test_el_orden_de_los_plugins_habilitados_es_semantico(tmp_path: pathlib.Path) -> None:
    """Reordenar líneas habilitadas cambia el estado (es el orden del perfil)."""
    primero = _crear_perfil(
        tmp_path / "a",
        plugins=_MO2_HEADER + b"*A.esp\r\n*B.esp\r\n",
    )
    segundo = _crear_perfil(
        tmp_path / "b",
        plugins=_MO2_HEADER + b"*B.esp\r\n*A.esp\r\n",
    )

    assert primero.challenge().profile_fingerprint != segundo.challenge().profile_fingerprint


