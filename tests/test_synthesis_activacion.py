def test_to_dict_declara_que_no_se_aplico(tmp_path: pathlib.Path) -> None:
    perfil = _perfil(tmp_path, modlist="+Otro Mod\n", plugins=_PLUGINS_OK)

    datos = calcular_diff_de_activacion(perfil=perfil, salidas=["Synthesis.esp"]).to_dict()

    assert datos["aplicado"] is False
    assert datos["mod"] == SYNTHESIS_MANAGED_MOD_NAME
    assert datos["estado_del_mod"] == "ausente"
    assert isinstance(datos["cambios_requeridos"], list)


# Primitivas que mutan el sistema de archivos. Enumerar la familia: un helper nuevo que escriba
# ``plugins.txt`` desde este módulo rompe el ancla hasta PR-5 (activación transaccional).
_MUTADORES = frozenset(
    {
        "write_text",
        "write_bytes",
        "replace",
        "rename",
        "unlink",
        "rmdir",
        "mkdir",
        "touch",
        "chmod",
        "remove",
        "rmtree",
        "move",
        "copy",
        "copy2",
        "copyfile",
        "copytree",
        "truncate",
        "symlink_to",
        "hardlink_to",
    }
)


def test_el_modulo_no_contiene_primitivas_de_escritura() -> None:
    arbol = ast.parse(_MODULO.read_text(encoding="utf-8"))
    llamadas = [n for n in ast.walk(arbol) if isinstance(n, ast.Call)]

    mutadoras = sorted(
        ast.unparse(c.func) for c in llamadas if isinstance(c.func, ast.Attribute) and c.func.attr in _MUTADORES
    )
    aperturas = [
        c
        for c in llamadas
        if isinstance(c.func, (ast.Name, ast.Attribute)) and ast.unparse(c.func) in {"open", "io.open", "os.open"}
    ]

    assert mutadoras == []
    assert aperturas == [], "el diff lee con Path.read_text; ninguna apertura explícita (ni de lectura)"


