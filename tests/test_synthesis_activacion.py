"""PR-2b3 (ADR 0019 §2.3): diff de activación/contigüidad de Synthesis en SOLO LECTURA.

Hasta PR-5 el perfil de MO2 no es quiescente: ``modlist.txt`` y ``plugins.txt`` se conservan byte a
byte y Sky-Claw solo informa qué habría que cambiar para activar ``+Sky-Claw Synthesis Output`` y
dejar los splits ``<Grupo>.esp``, ``<Grupo>_2.esp``… adyacentes, ordenados y antes de los plugins de
LOD (``DynDOLOD.esm``/``DynDOLOD.esp``/``Occlusion.esp``).
"""

from __future__ import annotations

import ast
import pathlib

import pytest

from sky_claw.local.tools.output_targets import SYNTHESIS_MANAGED_MOD_NAME
from sky_claw.local.tools.synthesis_activacion import DiffDeActivacionError, calcular_diff_de_activacion

_MODULO = pathlib.Path(__file__).resolve().parents[1] / "sky_claw" / "local" / "tools" / "synthesis_activacion.py"


def _perfil(tmp_path: pathlib.Path, *, modlist: str, plugins: str) -> pathlib.Path:
    perfil = tmp_path / "profiles" / "Default"
    perfil.mkdir(parents=True)
    (perfil / "modlist.txt").write_text(modlist, encoding="utf-8")
    (perfil / "plugins.txt").write_text(plugins, encoding="utf-8")
    return perfil


_MODLIST_OK = f"# This file was automatically generated by Mod Organizer.\n+{SYNTHESIS_MANAGED_MOD_NAME}\n+Otro Mod\n"
_PLUGINS_OK = "# comentario\n*Skyrim.esm\n*Synthesis.esp\n*Synthesis_2.esp\n*Otro.esp\n*DynDOLOD.esp\n*Occlusion.esp\n"


def test_perfil_ya_activado_y_contiguo_no_requiere_cambios(tmp_path: pathlib.Path) -> None:
    # Arrange
    perfil = _perfil(tmp_path, modlist=_MODLIST_OK, plugins=_PLUGINS_OK)

    # Act
    diff = calcular_diff_de_activacion(perfil=perfil, salidas=["Synthesis_2.esp", "Synthesis.esp"])

    # Assert
    assert diff.estado_del_mod == "habilitado"
    assert diff.plugins_ausentes == ()
    assert diff.plugins_inactivos == ()
    assert diff.grupos_no_contiguos == ()
    assert diff.despues_de_lod == ()
    assert diff.cambios_requeridos == ()
    assert diff.aplicado is False


@pytest.mark.parametrize(
    ("linea", "estado"),
    [
        (f"-{SYNTHESIS_MANAGED_MOD_NAME}\n", "deshabilitado"),
        ("+Otro Mod\n", "ausente"),
        # MO2 compara nombres de mod sin distinguir mayúsculas en Windows.
        (f"+{SYNTHESIS_MANAGED_MOD_NAME.upper()}\n", "habilitado"),
    ],
)
def test_estado_del_mod_administrado(tmp_path: pathlib.Path, linea: str, estado: str) -> None:
    perfil = _perfil(tmp_path, modlist=linea, plugins=_PLUGINS_OK)

    diff = calcular_diff_de_activacion(perfil=perfil, salidas=["Synthesis.esp"])

    assert diff.estado_del_mod == estado
    assert (diff.cambios_requeridos == ()) is (estado == "habilitado")


def test_plugins_ausentes_e_inactivos_se_informan_por_separado(tmp_path: pathlib.Path) -> None:
    perfil = _perfil(tmp_path, modlist=_MODLIST_OK, plugins="*Skyrim.esm\nsynthesis.esp\n*DynDOLOD.esp\n")

    diff = calcular_diff_de_activacion(perfil=perfil, salidas=["Synthesis.esp", "Synthesis_2.esp"])

    assert diff.plugins_inactivos == ("Synthesis.esp",)
    assert diff.plugins_ausentes == ("Synthesis_2.esp",)
    assert len(diff.cambios_requeridos) == 2


def test_splits_separados_o_desordenados_no_son_contiguos(tmp_path: pathlib.Path) -> None:
    plugins = "*Synthesis_2.esp\n*Synthesis.esp\n*Otro.esp\n*Bash_2.esp\n*Bash.esp\n*Medio.esp\n*Bash_3.esp\n"
    perfil = _perfil(tmp_path, modlist=_MODLIST_OK, plugins=plugins)

    diff = calcular_diff_de_activacion(
        perfil=perfil, salidas=["Synthesis.esp", "Synthesis_2.esp", "Bash.esp", "Bash_2.esp", "Bash_3.esp"]
    )

    assert diff.grupos_no_contiguos == ("Bash", "Synthesis")


def test_salida_despues_de_los_plugins_de_lod(tmp_path: pathlib.Path) -> None:
    plugins = "*Skyrim.esm\n*DynDOLOD.esm\n*Synthesis.esp\n*Occlusion.esp\n"
    perfil = _perfil(tmp_path, modlist=_MODLIST_OK, plugins=plugins)

    diff = calcular_diff_de_activacion(perfil=perfil, salidas=["Synthesis.esp"])

    assert diff.despues_de_lod == ("Synthesis.esp",)
    assert diff.cambios_requeridos != ()


def test_un_grupo_cuyo_nombre_termina_en_numero_no_se_confunde_con_un_split(tmp_path: pathlib.Path) -> None:
    # ``Grupo_2.esp`` solo es split de ``Grupo`` si ``Grupo.esp`` también es salida de la corrida.
    plugins = "*Grupo_2.esp\n*Otro.esp\n*Synthesis.esp\n"
    perfil = _perfil(tmp_path, modlist=_MODLIST_OK, plugins=plugins)

    diff = calcular_diff_de_activacion(perfil=perfil, salidas=["Grupo_2.esp", "Synthesis.esp"])

    assert diff.grupos_no_contiguos == ()


def test_el_diff_no_modifica_modlist_ni_plugins(tmp_path: pathlib.Path) -> None:
    perfil = _perfil(tmp_path, modlist="+Otro Mod\n", plugins="*Synthesis_2.esp\n*DynDOLOD.esm\n*Synthesis.esp\n")
    antes = {n: (perfil / n).read_bytes() for n in ("modlist.txt", "plugins.txt")}
    mtimes = {n: (perfil / n).stat().st_mtime_ns for n in antes}

    diff = calcular_diff_de_activacion(perfil=perfil, salidas=["Synthesis.esp", "Synthesis_2.esp"])

    assert diff.cambios_requeridos != ()
    assert {n: (perfil / n).read_bytes() for n in antes} == antes
    assert {n: (perfil / n).stat().st_mtime_ns for n in antes} == mtimes
    assert sorted(p.name for p in perfil.iterdir()) == ["modlist.txt", "plugins.txt"]


@pytest.mark.parametrize("faltante", ["modlist.txt", "plugins.txt"])
def test_sin_archivo_del_perfil_falla_cerrado(tmp_path: pathlib.Path, faltante: str) -> None:
    perfil = _perfil(tmp_path, modlist=_MODLIST_OK, plugins=_PLUGINS_OK)
    (perfil / faltante).unlink()

    with pytest.raises(DiffDeActivacionError, match=faltante.split(".")[0]):
        calcular_diff_de_activacion(perfil=perfil, salidas=["Synthesis.esp"])


