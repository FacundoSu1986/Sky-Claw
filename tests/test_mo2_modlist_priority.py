def test_h1_c_canary_source(tmp_path: pathlib.Path) -> None:
    """TEST H1-C: para source_mod, sólo mods de mayor prioridad real y overwrite eclipsan.

    Un mod de menor prioridad con el mismo archivo NO invalida el canary.
    Un mod de mayor prioridad real SÍ invalida el canary.
    """
    data_root = tmp_path / "MO2"
    mods_dir = data_root / "mods"
    profile_dir = data_root / "profiles" / "Default"
    profile_dir.mkdir(parents=True)
    physical_data = tmp_path / "game" / "Data"
    physical_data.mkdir(parents=True)

    # High > TexGen Output > Low
    modlist = profile_dir / "modlist.txt"
    modlist.write_text("+High\n+TexGen Output\n+Low\n", encoding="utf-8")

    texgen = mods_dir / "TexGen Output" / "textures"
    texgen.mkdir(parents=True)
    (texgen / "canary.dds").write_bytes(b"CANARY_BYTES")

    low = mods_dir / "Low" / "textures"
    low.mkdir(parents=True)
    (low / "canary.dds").write_bytes(b"CANARY_BYTES")

    high = mods_dir / "High" / "textures"
    high.mkdir(parents=True)

    # 1. Low contiene canary.dds pero es inferior: el canary de TexGen Output sigue siendo válido
    challenge = build_attestation_challenge_for_source(
        source_mod="TexGen Output",
        data_root=data_root,
        mods_dir=mods_dir,
        profile="Default",
        physical_data_dir=physical_data,
    )
    assert challenge.source_mod == "TexGen Output"
    assert challenge.relative_path.as_posix() == "textures/canary.dds"

    # 2. High contiene canary.dds y es superior: eclipsa el canary -> error
    (high / "canary.dds").write_bytes(b"OTHER_BYTES")
    with pytest.raises(VfsAttestationError, match="queda eclipsado"):
        build_attestation_challenge_for_source(
            source_mod="TexGen Output",
            data_root=data_root,
            mods_dir=mods_dir,
            profile="Default",
            physical_data_dir=physical_data,
        )


def test_h1_d_free_canary_with_overwrite(tmp_path: pathlib.Path) -> None:
    """TEST H1-D: selección libre de canary (source_mod=None) respeta precedencia de overwrite.

    Si overwrite contiene el archivo que un mod candidataría como canary,
    overwrite lo eclipsa y dicho archivo NO es elegible como canary.
    """
    data_root = tmp_path / "MO2"
    mods_dir = data_root / "mods"
    profile_dir = data_root / "profiles" / "Default"
    profile_dir.mkdir(parents=True)
    physical_data = tmp_path / "game" / "Data"
    physical_data.mkdir(parents=True)

    modlist = profile_dir / "modlist.txt"
    modlist.write_text("+ModA\n+ModB\n", encoding="utf-8")

    # ModA tiene canary1.dds
    mod_a = mods_dir / "ModA" / "textures"
    mod_a.mkdir(parents=True)
    (mod_a / "canary1.dds").write_bytes(b"BYTES_A")

    # ModB tiene canary2.dds
    mod_b = mods_dir / "ModB" / "textures"
    mod_b.mkdir(parents=True)
    (mod_b / "canary2.dds").write_bytes(b"BYTES_B")

    # overwrite contiene canary1.dds (eclipsando ModA)
    overwrite = data_root / "overwrite" / "textures"
    overwrite.mkdir(parents=True)
    (overwrite / "canary1.dds").write_bytes(b"BYTES_OVERWRITE")

    # El canary libre NO puede elegir canary1.dds de ModA porque overwrite lo eclipsa;
    # debe elegir canary2.dds de ModB (que no está en overwrite).
    challenge = build_attestation_challenge(
        profile="Default",
        data_root=data_root,
        mods_dir=mods_dir,
        physical_data_dir=physical_data,
    )
    assert challenge.source_mod == "ModB"
    assert challenge.relative_path.as_posix() == "textures/canary2.dds"


