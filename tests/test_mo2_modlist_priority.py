    enabled = read_enabled_mods(clon_modlist)
    assert enabled == ("OtroMod", "OtroModQueTieneGrassControl", "SkyClaw - Grass Precache Config")
    assert enabled[-1] == "SkyClaw - Grass Precache Config"


