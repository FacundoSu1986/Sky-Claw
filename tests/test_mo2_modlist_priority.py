def test_golden_real_mo2_modlist_format(tmp_path: pathlib.Path) -> None:
    """TEST GOLDEN: fixture realista con el formato exacto en disco que escribe MO2.

    En modlist.txt, la primera línea habilitada es la de mayor prioridad.
    read_enabled_mods() devuelve la tupla en orden de prioridad creciente
    (menor a mayor).
    """
    modlist = tmp_path / "modlist.txt"
    modlist.write_text(
        "# This file was automatically generated by Mod Organizer.\r\n"
        "+HighPriorityMod\r\n"
        "+TexGen Output\r\n"
        "+LowPriorityMod\r\n"
        "*separator_Textures\r\n"
        "-DisabledMod\r\n",
        encoding="utf-8-sig",
    )

    resultado = read_enabled_mods(modlist)
    assert resultado == ("LowPriorityMod", "TexGen Output", "HighPriorityMod")


def test_h1_a_effectivity(tmp_path: pathlib.Path) -> None:
    """TEST H1-A: efecto de la prioridad sobre el gate de efectividad del artifact.

    Escenario:
    High > TexGen Output > Low (en modlist.txt real: High primero, TexGen en medio, Low después).
    - Mismo path en Low con bytes diferentes: Low NO eclipsa TexGen Output.
    - Mismo path en High con bytes diferentes: High SÍ eclipsa TexGen Output -> BLOCK.
    """
    data_root = tmp_path / "MO2"
    mods_dir = data_root / "mods"
    profile_dir = data_root / "profiles" / "Default"
    profile_dir.mkdir(parents=True)

    modlist = profile_dir / "modlist.txt"
    modlist.write_text("+High\n+TexGen Output\n+Low\n", encoding="utf-8")

    artifact_root = mods_dir / "TexGen Output" / "textures"
    artifact_root.mkdir(parents=True)
    (artifact_root / "test.dds").write_bytes(b"AUTHORIZED_TEXGEN")

    low_dir = mods_dir / "Low" / "textures"
    low_dir.mkdir(parents=True)
    (low_dir / "test.dds").write_bytes(b"LOW_BYTES_DIFFERENT")

    high_dir = mods_dir / "High" / "textures"
    high_dir.mkdir(parents=True)

    enabled = read_enabled_mods(modlist)
    assert enabled == ("Low", "TexGen Output", "High")

    # Paso 1: Low tiene bytes diferentes pero prioridad inferior: NO eclipsa
    total = verificar_artifact_efectivo(
        artifact_root=artifact_root,
        mod_name="TexGen Output",
        mods_dir=mods_dir,
        data_root=data_root,
        enabled=enabled,
    )
    assert total == 1

    # Paso 2: High tiene bytes diferentes y prioridad superior: SÍ eclipsa -> BLOCK
    (high_dir / "test.dds").write_bytes(b"HIGH_BYTES_DIFFERENT")
    with pytest.raises(ModEffectivityError, match="High"):
        verificar_artifact_efectivo(
            artifact_root=artifact_root,
            mod_name="TexGen Output",
            mods_dir=mods_dir,
            data_root=data_root,
            enabled=enabled,
        )


