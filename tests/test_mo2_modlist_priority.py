"""H1 — Semántica de prioridad de modlist.txt de Mod Organizer 2.

Valida y congela la relación contractual entre el formato físico en disco de MO2
y la representación interna normalizada de Sky-Claw:

1. FORMATO FÍSICO EN DISCO (MO2):
   ``Profile::doWriteModlist`` recorre ``m_ModIndexByPriority`` en reversa
   (``crbegin()`` a ``crend()``), por lo que en disco:
   - Primera línea habilitada (``+Nombre``) = MAYOR prioridad entre mods regulares.
   - Última línea habilitada = MENOR prioridad entre mods regulares.
   - El overlay de ``overwrite`` permanece por encima de los mods regulares.

2. NORMALIZACIÓN CENTRAL EN EL BOUNDARY (read_enabled_mods):
   ``read_enabled_mods()`` invierte ese orden al leer (``tuple(reversed(enabled))``)
   para que la representación interna consumida por todo el resto de Sky-Claw sea
   estrictamente CRECIENTE:
   - Índice 0 = menor prioridad.
   - Último índice = mayor prioridad (convención "último gana").

3. CONSUMIDORES UNIFICADOS:
   - ``mod_effectivity.py`` (los superiores son ``enabled[indice + 1 :]``).
   - ``vfs_attestation.py`` (selección de canaries con overwrite y superiores).
   - ``asset_scanner.py`` (delega en ``read_enabled_mods``).
"""

